#!/usr/bin/env python3
"""Generate every app's theme file from theme/tokens.json (stdlib only).

One palette for the whole suite: the Jess dashboard, the Homepage launcher,
Home Assistant and Grist. Edit tokens.json, run `python3 theme/build.py`, commit
the regenerated files. CI regenerates and fails on drift (like dashgen), so the
outputs below must never be hand-edited:

  frontend/src/styles/tokens.css   CSS variables the dashboard's Tailwind reads
  frontend/src/styles/theme-meta.ts  per-theme background for theme-color/manifest
  theme/dist/homepage.css          -> <homepage>/config/custom.css
  theme/dist/home-assistant.yaml   -> <ha config>/themes/jess_suite.yaml
  theme/dist/grist.css             -> mounted as /grist/static/custom.css

How to apply each one: theme/README.md.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "theme" / "tokens.json"
DIST = ROOT / "theme" / "dist"
FRONTEND_CSS = ROOT / "frontend" / "src" / "styles" / "tokens.css"
FRONTEND_META = ROOT / "frontend" / "src" / "styles" / "theme-meta.ts"

HEADER = "GENERATED by theme/build.py from theme/tokens.json — do not edit by hand."


# ---------------------------------------------------------------- color math
def rgb(hex_color: str) -> tuple[int, int, int]:
    h = hex_color.lstrip("#")
    if len(h) != 6:
        raise ValueError(f"expected #rrggbb, got {hex_color!r}")
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)


def to_hex(c: tuple[float, float, float]) -> str:
    return "#" + "".join(f"{round(max(0, min(255, v))):02x}" for v in c)


def mix(a: str, b: str, t: float) -> str:
    """t=0 → a, t=1 → b."""
    ca, cb = rgb(a), rgb(b)
    return to_hex(tuple(x + (y - x) * t for x, y in zip(ca, cb, strict=True)))


def channels(hex_color: str) -> str:
    r, g, b = rgb(hex_color)
    return f"{r} {g} {b}"


def rgba(hex_color: str, alpha: float) -> str:
    r, g, b = rgb(hex_color)
    return f"rgba({r}, {g}, {b}, {alpha:g})"


def hex_alpha(hex_color: str, alpha: float) -> str:
    return f"{hex_color}{round(alpha * 255):02x}"


# ------------------------------------------------------------- color listing
def flat_colors(t: dict) -> dict[str, str]:
    """name → hex for every themable color, in a stable order."""
    out: dict[str, str] = {}
    for k, v in t["brand"].items():
        out["brand" if k == "DEFAULT" else f"brand-{k}"] = v
    out["on-brand"] = t["on-brand"]
    for group in ("surface", "content"):
        for k, v in t[group].items():
            out[f"{group}-{k}"] = v
    out["ink"] = t["ink"]
    out.update(t["status"])
    for k, v in t["accent"].items():
        out[f"accent-{k}"] = v
    return out


# ------------------------------------------------------------ dashboard CSS
def theme_block(t: dict, indent: str) -> str:
    lines = [f"color-scheme: {t['scheme']};"]
    lines += [f"--c-{name}: {channels(v)};" for name, v in flat_colors(t).items()]
    for k, a in t["line"].items():
        name = "--line" if k == "DEFAULT" else f"--line-{k}"
        lines.append(f"{name}: rgb(var(--c-ink) / {a:g});")
    lines.append(f"--glow: rgb(var(--c-brand) / {t['glow']:g});")
    lines.append(f"--shadow-card: {t['shadow']['card']};")
    lines.append(f"--shadow-glow: {t['shadow']['glow']};")
    return "\n".join(indent + ln for ln in lines)


def build_frontend_css(tok: dict) -> str:
    dark, light = tok["themes"]["dark"], tok["themes"]["light"]
    radius = "\n".join(f"  --radius-{k}: {v}px;" for k, v in tok["radius"].items())
    aliases = "\n".join(
        f"  --{name}: rgb(var(--c-{name}));"
        for name in flat_colors(dark)
        if name.startswith(("surface-", "content-")) or name in ("brand", "brand-hover")
    )
    return f"""/* {HEADER}
 *
 * Colors are bare RGB channels (--c-*) so Tailwind opacity modifiers work:
 * tailwind.config.ts maps e.g. `brand` → rgb(var(--c-brand) / <alpha-value>).
 *
 * data-theme="…" on <html> (or any element, to scope a preview) picks the palette:
 *   dark   (also the default with no attribute) — the original Jess look
 *   light
 *   system — follows the OS via prefers-color-scheme
 */

:root,
[data-theme='dark'] {{
{theme_block(dark, "  ")}
}}

[data-theme='light'] {{
{theme_block(light, "  ")}
}}

@media (prefers-color-scheme: light) {{
  [data-theme='system'] {{
{theme_block(light, "    ")}
  }}
}}

:root {{
  --font-sans: {tok["font"]["sans"]};
  --font-mono: {tok["font"]["mono"]};
{radius}

  /* Solid-color aliases for plain CSS (var(--surface-raised), …). */
{aliases}

  /* Back-compat aliases (older code references these). */
  --bg-primary: var(--surface-base);
  --bg-raised: var(--surface-raised);
  --bg-overlay: var(--surface-overlay);
  --text-primary: var(--content-primary);
  --text-secondary: var(--content-secondary);
  --accent: var(--brand);
}}
"""


def build_frontend_meta(tok: dict) -> str:
    bg = {m: t["surface"]["base"] for m, t in tok["themes"].items()}
    return f"""// {HEADER}
// Page background per theme — for places CSS variables can't reach
// (<meta name="theme-color">, the PWA manifest).
export const THEME_BACKGROUND = {{ dark: '{bg["dark"]}', light: '{bg["light"]}' }} as const;
"""


# ----------------------------------------------------------------- Homepage
def homepage_ramp(tok: dict) -> dict[str, str]:
    """gethomepage's 50–900 palette. It paints the page with 800 in dark mode
    and 50 in light mode, text with the opposite end, so anchor those on the
    suite's surfaces and interpolate the rest."""
    d, lt = tok["themes"]["dark"], tok["themes"]["light"]
    base_d, base_l = d["surface"]["base"], lt["surface"]["base"]
    return {
        "50": base_l,
        "100": d["content"]["primary"],
        "200": mix(d["content"]["primary"], d["content"]["secondary"], 0.5),
        "300": d["content"]["secondary"],
        "400": mix(d["content"]["secondary"], d["content"]["muted"], 0.5),
        "500": d["content"]["muted"],
        "600": mix(d["surface"]["overlay"], d["content"]["muted"], 0.3),
        "700": d["surface"]["overlay"],
        "800": base_d,
        "900": d["surface"]["inset"],
    }


def build_homepage_css(tok: dict) -> str:
    d, lt = tok["themes"]["dark"], tok["themes"]["light"]
    ramp = "\n".join(f"  --color-{k}: {channels(v)};" for k, v in homepage_ramp(tok).items())
    r = tok["radius"]
    return f"""/* {HEADER}
 * Jess suite theme for gethomepage — copy to <homepage>/config/custom.css.
 * :root:root outranks the .theme-<color> class settings.yaml puts on <html>.
 */
:root:root {{
{ramp}
  --color-logo-start: {channels(d["brand"]["DEFAULT"])};
  --color-logo-stop: {channels(d["brand"]["700"])};
}}

html,
body {{
  font-family: {tok["font"]["sans"]};
}}

.dark body {{
  background: radial-gradient(900px circle at 100% -10%, {rgba(d["brand"]["DEFAULT"], d["glow"])}, transparent 55%);
}}

.light body {{
  background: radial-gradient(900px circle at 100% -10%, {rgba(lt["brand"]["DEFAULT"], lt["glow"])}, transparent 55%);
}}

.service-card,
.bookmark {{
  border-radius: {r["lg"]}px;
}}

.dark .service-card {{
  background-color: {rgba(d["surface"]["raised"], 0.82)};
  border: 1px solid {rgba(d["ink"], d["line"]["DEFAULT"])};
  box-shadow: {d["shadow"]["card"]};
  backdrop-filter: blur(12px);
}}

.light .service-card {{
  background-color: {lt["surface"]["raised"]};
  border: 1px solid {rgba(lt["ink"], lt["line"]["DEFAULT"])};
  box-shadow: {lt["shadow"]["card"]};
}}

.dark .service-card:hover {{
  box-shadow: {d["shadow"]["glow"]};
}}

.light .service-card:hover {{
  box-shadow: {lt["shadow"]["glow"]};
}}

.service-group-name,
.bookmark-group-name {{
  letter-spacing: 0.06em;
  text-transform: uppercase;
  font-size: 0.75rem;
  font-weight: 600;
}}
"""


# ----------------------------------------------------------- Home Assistant
def ha_mode(t: dict) -> dict[str, str]:
    s, c, st = t["surface"], t["content"], t["status"]
    line = rgba(t["ink"], t["line"]["DEFAULT"])
    return {
        "primary-color": t["brand"]["DEFAULT"],
        "dark-primary-color": t["brand"]["700"],
        "light-primary-color": t["brand"]["50"],
        "accent-color": t["brand"]["DEFAULT"],
        "text-primary-color": t["on-brand"],
        "primary-background-color": s["base"],
        "secondary-background-color": s["overlay"],
        "card-background-color": s["raised"],
        "ha-card-background": s["raised"],
        "ha-card-border-color": line,
        "ha-card-box-shadow": t["shadow"]["card"],
        "ha-dialog-surface-background": s["raised"],
        "primary-text-color": c["primary"],
        "secondary-text-color": c["secondary"],
        "disabled-text-color": c["muted"],
        "divider-color": line,
        "app-header-background-color": s["base"],
        "app-header-text-color": c["primary"],
        "app-header-border-bottom": f"1px solid {line}",
        "sidebar-background-color": s["base"],
        "sidebar-text-color": c["secondary"],
        "sidebar-icon-color": c["muted"],
        "sidebar-selected-text-color": t["brand"]["DEFAULT"],
        "sidebar-selected-icon-color": t["brand"]["DEFAULT"],
        "input-fill-color": s["inset"],
        "mdc-text-field-fill-color": s["inset"],
        "code-editor-background-color": s["inset"],
        "success-color": st["success"],
        "warning-color": st["warning"],
        "error-color": st["danger"],
        "info-color": st["info"],
        "state-icon-active-color": t["brand"]["DEFAULT"],
        "switch-checked-color": t["brand"]["DEFAULT"],
        "switch-checked-button-color": t["brand"]["DEFAULT"],
        "switch-checked-track-color": t["brand"]["DEFAULT"],
    }


def yaml_str(v: str) -> str:
    # A JSON string is a valid YAML double-quoted scalar (escapes included).
    return json.dumps(v, ensure_ascii=False)


def build_ha_yaml(tok: dict) -> str:
    r = tok["radius"]
    shared = {
        "primary-font-family": tok["font"]["sans"],
        "paper-font-common-base_-_font-family": "var(--primary-font-family)",
        "ha-card-border-radius": f"{r['lg']}px",
        "ha-dialog-border-radius": f"{r['xl']}px",
        "ha-card-border-width": "1px",
    }
    out = [
        f"# {HEADER}",
        "# Home Assistant theme — copy to <ha config>/themes/jess_suite.yaml, make sure",
        "# configuration.yaml has `frontend: themes: !include_dir_merge_named themes`,",
        "# then pick 'Jess Suite' in your HA profile (Theme → Jess Suite, Auto mode).",
        f"{yaml_str(tok['name'])}:",
    ]
    out += [f"  {k}: {yaml_str(v)}" for k, v in shared.items()]
    out.append("  modes:")
    for mode in ("light", "dark"):
        out.append(f"    {mode}:")
        out += [f"      {k}: {yaml_str(v)}" for k, v in ha_mode(tok["themes"][mode]).items()]
    return "\n".join(out) + "\n"


# -------------------------------------------------------------------- Grist
def grist_vars(t: dict, tok: dict) -> dict[str, str]:
    s, c, st, b = t["surface"], t["content"], t["status"], t["brand"]
    sel = lambda a: hex_alpha(b["DEFAULT"], a)  # noqa: E731 — tiny local helper
    dark = t["scheme"] == "dark"
    return {
        "--grist-theme-body": c["primary"],
        "--grist-theme-emphasis": c["primary"],
        "--grist-theme-bg-default": s["raised"],
        "--grist-theme-bg-secondary": s["base"],
        "--grist-theme-bg-tertiary": hex_alpha(t["ink"], 0.08),
        "--grist-theme-bg-emphasis": mix(s["overlay"], c["muted"], 0.35) if dark else c["primary"],
        "--grist-theme-decoration": mix(s["raised"], t["ink"], t["line"]["strong"]),
        "--grist-theme-decoration-secondary": mix(s["raised"], t["ink"], t["line"]["DEFAULT"]),
        "--grist-theme-decoration-tertiary": mix(s["raised"], t["ink"], t["line"]["subtle"]),
        "--grist-theme-primary": b["DEFAULT"],
        "--grist-theme-primary-muted": b["600"],
        "--grist-theme-primary-dim": b["700"],
        "--grist-theme-primary-emphasis": b["50"],
        "--grist-theme-secondary": c["muted"],
        "--grist-theme-secondary-muted": c["secondary"],
        "--grist-theme-token-cursor": b["DEFAULT"],
        "--grist-theme-token-cursor-inactive": mix(s["raised"], b["DEFAULT"], 0.45),
        "--grist-theme-token-selection": sel(0.15),
        "--grist-theme-token-selection-opaque": mix(s["raised"], b["DEFAULT"], 0.15),
        "--grist-theme-token-selection-darker-opaque": mix(s["raised"], b["DEFAULT"], 0.2),
        "--grist-theme-token-selection-darker": sel(0.25),
        "--grist-theme-token-selection-darkest": sel(0.35),
        "--grist-theme-backdrop": hex_alpha(tok["themes"]["dark"]["surface"]["inset"], 0.8),
        "--grist-theme-error": st["danger"],
        "--grist-theme-warning": st["warning"],
        "--grist-theme-info": st["info"],
    }


def build_grist_css(tok: dict) -> str:
    r = tok["radius"]

    def block(theme: str, t: dict) -> str:
        body = "\n".join(f"    {k}: {v};" for k, v in grist_vars(t, tok).items())
        return f"  :root[data-grist-theme='{theme}'] {{\n{body}\n  }}"

    return f"""/* {HEADER}
 * Jess suite theme for Grist — mounted as /grist/static/custom.css with
 * APP_STATIC_INCLUDE_CUSTOM_CSS=true (see grist/docker-compose.yml).
 * Variable names: /grist/static/custom.css inside the image (Grist 1.7.x).
 */
@layer grist-custom {{
  :root {{
    --grist-theme-font-family: {tok["font"]["sans"]};
    --grist-theme-control-border-radius: {r["sm"]}px;
  }}

{block("GristLight", tok["themes"]["light"])}

{block("GristDark", tok["themes"]["dark"])}
}}
"""


# --------------------------------------------------------------------- main
def outputs(tok: dict) -> dict[Path, str]:
    return {
        FRONTEND_CSS: build_frontend_css(tok),
        FRONTEND_META: build_frontend_meta(tok),
        DIST / "homepage.css": build_homepage_css(tok),
        DIST / "home-assistant.yaml": build_ha_yaml(tok),
        DIST / "grist.css": build_grist_css(tok),
    }


_HEX = re.compile(r"#[0-9a-fA-F]{6}")
_SHADOW = re.compile(r"[0-9a-z.,()\s-]+")
_FONT = re.compile(r'[A-Za-z0-9 ,"-]+')


def validate(tok: dict) -> None:
    """Token values are pasted into CSS/YAML verbatim; refuse anything that
    could break out of a declaration (url(, @import, braces, semicolons)."""
    for name, value in tok["font"].items():
        if not _FONT.fullmatch(value):
            raise ValueError(f"font.{name}: unexpected characters in {value!r}")
    for name, value in tok["radius"].items():
        if not isinstance(value, int) or not 0 <= value <= 64:
            raise ValueError(f"radius.{name}: expected an int 0–64, got {value!r}")
    for mode, t in tok["themes"].items():
        for name, value in flat_colors(t).items():
            if not _HEX.fullmatch(value):
                raise ValueError(f"themes.{mode}.{name}: expected #rrggbb, got {value!r}")
        for name, value in t["shadow"].items():
            if not _SHADOW.fullmatch(value) or "url" in value:
                raise ValueError(f"themes.{mode}.shadow.{name}: unexpected characters")
        for name, value in [*t["line"].items(), ("glow", t["glow"])]:
            if not isinstance(value, (int, float)) or not 0 <= value <= 1:
                raise ValueError(f"themes.{mode}.{name}: expected an opacity 0–1, got {value!r}")


def main() -> None:
    tok = json.loads(TOKENS.read_text(encoding="utf-8"))
    validate(tok)
    for path, text in outputs(tok).items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
